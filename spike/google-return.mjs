import { chromium } from 'playwright';
import { writeFileSync } from 'node:fs';
import { encodeTfs } from './tfs.mjs';
const tfs = encodeTfs([{ date: '2026-11-07', from: 'BRI', to: 'AMS' }, { date: '2026-11-08', from: 'AMS', to: 'BRI' }]);
const browser = await chromium.launch();
const page = await browser.newPage({ locale: 'it-IT' });
await page.goto(`https://www.google.com/travel/flights/search?tfs=${tfs}&hl=it&gl=IT&curr=EUR`, { waitUntil: 'domcontentloaded' });
const reject = page.getByRole('button', { name: /Rifiuta tutto/i });
if (await reject.count()) await reject.first().click();
const sel = page.locator('[aria-label^="A partire dal prezzo totale"]');
await sel.first().waitFor({ timeout: 20000 });
const items = await page.locator('li').evaluateAll((els) => els.map((e) => e.innerText.replace(/\s+/g, ' ')).filter((t) => /scalo|Diretto/.test(t)).slice(0, 3));
console.log('OUT ITEMS', items);
await sel.first().evaluate((e) => e.click());
await page.waitForTimeout(6000);
writeFileSync('test/fixtures/google-return.html', await page.content());
const labels = await page.locator('[aria-label*="prezzo totale"]').evaluateAll((els) => els.map((e) => e.getAttribute('aria-label')).slice(0, 3));
console.log('RET', labels);
console.log('URL', page.url().slice(0, 200));
await browser.close();
