import { chromium } from 'playwright';
import { writeFileSync } from 'node:fs';
import { encodeTfs } from './tfs.mjs';
const tfs = encodeTfs([{ date: '2026-11-07', from: 'BRI', to: 'AMS' }, { date: '2026-11-08', from: 'AMS', to: 'BRI' }]);
const browser = await chromium.launch();
const page = await browser.newPage({ locale: 'it-IT' });
await page.goto(`https://www.google.com/travel/flights/search?tfs=${tfs}&hl=it&gl=IT&curr=EUR`, { waitUntil: 'domcontentloaded' });
const reject = page.getByRole('button', { name: /Rifiuta tutto/i });
if (await reject.count()) await reject.first().click();
const SEL = '[aria-label^="A partire dal prezzo totale"]';
const grab = () => page.locator(SEL).evaluateAll((els) => els.map((e) => ({ label: e.getAttribute('aria-label'), text: (e.closest('li') || e).innerText.replace(/\s+/g, ' ') })));
await page.locator(SEL).first().waitFor({ timeout: 20000 });
const out = await grab();
writeFileSync('test/fixtures/google-outbound.json', JSON.stringify(out, null, 1));
await page.locator(SEL).nth(1).evaluate((e) => e.click());
await page.waitForTimeout(6000);
const ret = await grab();
writeFileSync('test/fixtures/google-return.json', JSON.stringify(ret, null, 1));
console.log(out.length, ret.length, out[0].text);
await browser.close();
